import { ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import { IsInt, IsOptional, Max, Min } from 'class-validator';

export class SummaryQueryDto {
  @ApiPropertyOptional({
    description: 'Calendar year in America/Bogota. Omit both year and month to get the current budget cycle.',
    example: 2026,
  })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(2000)
  @Max(2100)
  year?: number;

  @ApiPropertyOptional({
    description:
      'Calendar month 1–12 (America/Bogota). With month → that month; year only → whole year; neither → current cycle (since cycleStartedAt).',
    example: 9,
    minimum: 1,
    maximum: 12,
  })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(12)
  month?: number;
}
